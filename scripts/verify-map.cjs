const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
;(async () => {
  const browser = await chromium.launch({ headless: true, channel: process.env.UI_BROWSER_CHANNEL || undefined })
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'no-preference' })
    const checks = [], errors = [], tileRequests = []
    page.on('pageerror', error => errors.push(error.message))
    // Never pan/zoom a headless bot against the community tile servers.
    await page.route('https://tile.openstreetmap.org/**', route => { tileRequests.push(route.request().url()); return route.abort() })
    await page.addInitScript(() => {
      window.__mapRequests = 0
      const NativeWorker = window.Worker
      window.Worker = class extends NativeWorker { postMessage(data) { window.__mapRequests++; return super.postMessage(data) } }
    })
    await page.goto(process.env.UI_BASE_URL || 'http://127.0.0.1:4176/')
    const map = page.locator('.live-map'), slider = page.locator('#map-day')
    await map.waitFor({ timeout: 60000 })
    await map.scrollIntoViewIfNeeded()
    await page.waitForFunction(() => Number(document.querySelector('#map-day').value) >= 2)
    assert.ok(tileRequests.length > 0)
    await map.getByRole('button', { name: 'Pausar mapa', exact: true }).click()
    const stopped = await slider.inputValue()
    await page.waitForTimeout(700)
    assert.equal(await slider.inputValue(), stopped)
    checks.push('Auto-start on visibility, automatic street request, pause without recalculation')
    await map.getByRole('status').filter({ hasText: 'No se pudo cargar' }).waitFor()
    checks.push('Cartography failure retains all playback and counts; provider traffic intercepted')
    await map.getByRole('button', { name: 'Volver al día 0' }).click()
    assert.equal(await slider.inputValue(), '0')
    assert.match(await map.locator('.map-day-metrics').innerText(), /0\s+dosis/)
    const heat = map.locator('circle[fill="url(#infection-field)"]')
    assert.equal(await heat.count(), 5)
    const homesAtStart = Number(await heat.first().getAttribute('opacity'))
    await slider.focus(); for (let step = 0; step < 25; step++) await slider.press('ArrowRight')
    assert.ok(Number(await heat.first().getAttribute('opacity')) > homesAtStart)
    assert.match(await map.locator('.map-story').innerText(), /Hoy se usan/)
    assert.match(await map.locator('.map-day-metrics').innerText(), /dosis aún disponibles/)
    checks.push('Visible outbreak fields change with stored daily counts; vaccines, stock, cost and action update')
    await slider.focus(); await slider.press('End')
    assert.equal(await slider.inputValue(), '90')
    await map.getByLabel('Estrategia ilustrada').selectOption('none')
    assert.match(await map.locator('.map-day-metrics').innerText(), /0\s+dosis/)
    checks.push('Day 0/final and strategy use the actual stored trajectory and cumulative doses')
    await map.getByRole('button', { name: 'Acercar mapa' }).click()
    assert.match(await map.locator('.map-viewport-tools').innerText(), /zoom 14/)
    const before = await map.locator('.map-links line').first().getAttribute('x1')
    const canvas = map.locator('.map-canvas')
    await canvas.scrollIntoViewIfNeeded()
    const rect = await canvas.boundingBox()
    await page.mouse.move(rect.x + 20, rect.y + rect.height - 25)
    await page.mouse.down(); await page.mouse.move(rect.x + 110, rect.y + rect.height - 55, { steps: 4 }); await page.mouse.up()
    await page.waitForFunction(before => document.querySelector('.map-links line').getAttribute('x1') !== before, before)
    await map.getByRole('button', { name: 'Centrar Manta' }).click()
    assert.match(await map.locator('.map-viewport-tools').innerText(), /zoom 13/)
    await map.getByRole('button', { name: 'Colegio', exact: true }).click()
    await map.getByRole('heading', { name: 'Colegio · día 90', exact: true }).waitFor()
    assert.equal(await page.evaluate(() => window.__mapRequests), 1)
    checks.push('Zoom/pan/recenter/place inspection without restarting Monte Carlo')
    await slider.focus(); await slider.press('ArrowLeft')
    await map.getByRole('combobox', { name: /Velocidad/ }).selectOption('200')
    await map.getByRole('button', { name: 'Reproducir mapa', exact: true }).click()
    await page.waitForFunction(() => document.querySelector('#map-day').value === '90')
    await map.getByRole('button', { name: 'Reproducir mapa', exact: true }).waitFor()
    checks.push('Playback reaches the complete horizon and stops at the last day')
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await page.waitForFunction(() => [...document.querySelectorAll('.live-map button')].some(button => button.textContent === 'Reproducir mapa' && button.disabled))
    checks.push('Reduced motion disables autoplay while retaining manual controls')
    for (const [key, value] of Object.entries({ population: 100, initialInfected: 1, days: 12, runs: 2, vaccinesPerDay: 3, totalVaccines: 20 })) {
      const field = page.locator('[name=' + key + ']')
      if (!(await field.isVisible())) await page.locator('.advanced-controls > summary').click()
      await field.fill(String(value))
    }
    await page.getByRole('button', { name: 'Ejecutar simulación', exact: true }).click()
    await page.getByText('2 corridas · 12 días', { exact: false }).waitFor({ timeout: 60000 })
    await page.getByRole('button', { name: 'Evaluar cinco semillas' }).click()
    await page.getByText('Batería completa: cinco semillas evaluadas.', { exact: true }).waitFor({ timeout: 60000 })
    const first = await page.locator('.seed-validation tbody').innerText()
    await page.getByRole('button', { name: 'Evaluar cinco semillas' }).click()
    await page.getByText('Batería completa: cinco semillas evaluadas.', { exact: true }).waitFor({ timeout: 60000 })
    assert.equal(await page.locator('.seed-validation tbody').innerText(), first)
    const download = page.waitForEvent('download')
    await page.getByRole('button', { name: 'Exportar batería JSON' }).click()
    const json = JSON.parse(await fs.readFile(await (await download).path(), 'utf8'))
    assert.equal(json.completed, 5)
    checks.push('Five-seed real Worker batch repeats exactly and exports JSON')
    await page.setViewportSize({ width: 390, height: 844 })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
    checks.push('390px mobile viewport without horizontal page overflow')
    assert.deepEqual(errors, [])
    const out = process.env.UI_EVIDENCE_DIR || 'docs/evidencia/mapa'
    await fs.mkdir(out, { recursive: true })
    const record = { checkedAt: new Date().toISOString(), checks, errors, passed: checks.length, cartography: 'Requests aborted; no actual provider imagery verified' }
    await fs.writeFile(path.join(out, 'verificacion-mapa.json'), JSON.stringify(record, null, 2))
    await map.screenshot({ path: path.join(out, 'mapa-movil.png') })
    console.log(JSON.stringify(record, null, 2))
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
