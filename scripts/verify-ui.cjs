const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
;(async () => {
  const out = process.env.UI_EVIDENCE_DIR || 'docs/evidencia/ui'
  await fs.mkdir(out, { recursive: true })
  const browser = await chromium.launch({ headless: true, channel: process.env.UI_BROWSER_CHANNEL || undefined })
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, permissions: ['clipboard-read', 'clipboard-write'], reducedMotion: 'reduce' })
  const page = await context.newPage()
  const errors = [], checks = []
  page.on('pageerror', error => errors.push(error.message))
  await page.addInitScript(() => {
    window.__results = []; window.__requests = []; window.__progress = []
    const NativeWorker = window.Worker
    window.Worker = class extends NativeWorker {
      constructor(...args) {
        super(...args)
        this.addEventListener('message', ({ data }) => {
          if (data.type === 'result') window.__results.push(data.result)
          if (data.type === 'progress') window.__progress.push(data)
        })
      }
      postMessage(data) {
        if (window.__corruptNext) { data = structuredClone(data); data.input.population = 0; window.__corruptNext = false }
        window.__requests.push(data)
        return super.postMessage(data)
      }
    }
  })
  const wait = count => page.waitForFunction(count => window.__results.length === count, count, { timeout: 60000 })
  const latest = () => page.evaluate(() => window.__results.at(-1))
  const fill = (key, value) => page.locator('[name="' + key + '"]').fill(String(value))
  const run = () => page.getByRole('button', { name: 'Ejecutar simulación', exact: true }).click()
  try {
    await page.goto(process.env.UI_BASE_URL || 'http://127.0.0.1:4174/')
    await wait(1)
    const first = await latest()
    assert.equal(first.config.runs, 120)
    assert.equal(await page.locator('.range-band').count(), 3)
    assert.equal(await page.locator('.curve').count(), 3)
    assert.equal(await page.locator('.intervention-line').count(), 1)
    assert.ok(await page.evaluate(() => window.__progress.length > 0))
    await page.screenshot({ path: path.join(out, 'escritorio.png'), fullPage: true })
    checks.push('Default real, Worker de producción, progreso, tres curvas y bandas, marcador de intervención')
    await fill('seed', 87)
    assert.ok(await page.locator('.pending-banner').isVisible())
    assert.match(await page.locator('.applied-config').innerText(), /2026/)
    assert.equal(await page.evaluate(() => window.__requests.length), 1)
    await run(); await wait(2)
    const seeded = await latest()
    await run(); await wait(3)
    assert.deepEqual(await latest(), seeded)
    checks.push('Edición no recalcula ni cambia etiquetas; semilla 87 reproduce el resultado completo')
    await fill('seed', '')
    await run()
    assert.match(await page.getByRole('alert').innerText(), /Semilla/)
    assert.equal(await page.evaluate(() => window.__requests.length), 3)
    await fill('seed', 87)
    checks.push('Campo vacío se rechaza sin corregir la semilla a cero')
    await page.getByLabel('Escenarios de demostración').selectOption('escasez')
    assert.equal(await page.locator('[name=vaccinesPerDay]').inputValue(), '90')
    assert.equal(await page.locator('[name=totalVaccines]').inputValue(), '7560')
    await page.getByRole('button', { name: 'Contagio ×2' }).click()
    assert.equal(await page.locator('[name=transmissionRate]').inputValue(), '0.68')
    await page.getByRole('button', { name: 'Mitad del stock' }).click()
    assert.equal(await page.locator('[name=totalVaccines]').inputValue(), '3780')
    await page.getByRole('button', { name: 'Restablecer escenario oficial' }).click()
    await fill('totalVaccines', 0)
    await run(); await wait(4)
    const zero = await latest()
    assert.deepEqual(zero.targeted.timeline, zero.none.timeline)
    assert.deepEqual(zero.random.timeline, zero.none.timeline)
    assert.match(await page.locator('.decision').innerText(), /No hay vacunación/)
    checks.push('Presets, sorpresas acumulativas, restablecer y stock cero con tres trayectorias idénticas')
    await fill('population', 50000); await fill('days', 180); await fill('runs', 300)
    await fill('vaccinesPerDay', 2000); await fill('totalVaccines', 1000000)
    await run()
    await fill('seed', 99)
    assert.ok(await page.getByText('Editaste los controles durante el cálculo.', { exact: false }).isVisible())
    await page.getByRole('button', { name: 'Cancelar ejecución' }).click()
    assert.equal((await latest()).config.totalVaccines, 0)
    await page.getByRole('button', { name: 'Restablecer escenario oficial' }).click()
    await run(); await wait(5)
    assert.deepEqual(await latest(), first)
    checks.push('Cálculo pesado mantiene controles, captura configuración, permite cancelar y reejecutar')
    await page.evaluate(() => { window.__corruptNext = true })
    await run()
    await page.getByRole('alert').waitFor()
    assert.match(await page.getByRole('alert').innerText(), /Población/)
    assert.deepEqual(await latest(), first)
    checks.push('Error real del motor desde Worker conserva el resultado previo')
    const downloadPromise = page.waitForEvent('download')
    await page.getByRole('button', { name: 'Exportar JSON' }).click()
    const download = await downloadPromise
    const exported = JSON.parse(await fs.readFile(await download.path(), 'utf8'))
    assert.equal(exported.algorithmVersion, 'seir-places-2.0.0')
    assert.deepEqual(exported.config, first.config)
    assert.deepEqual(exported.targeted, first.targeted)
    checks.push('JSON descargado incluye versión, parámetros y resultados reales')
    await page.getByRole('button', { name: 'Copiar enlace del escenario' }).click()
    const share = await page.evaluate(() => navigator.clipboard.readText())
    const sharedPage = await context.newPage()
    await sharedPage.goto(share)
    await sharedPage.getByRole('heading', { name: 'Resultado simulado · semilla 2026', exact: true }).waitFor()
    await sharedPage.close()
    checks.push('Enlace compartido valida y reproduce la configuración')
    const audit = JSON.parse(await fs.readFile('docs/evidencia/sensibilidad.json', 'utf8'))
    assert.ok(audit.negativeExample)
    for (const [key, value] of Object.entries(audit.negativeExample.config)) {
      if (key === 'outbreakLocation') await page.locator('[name=outbreakLocation]').selectOption(value)
      else await fill(key, value)
    }
    await run(); await wait(6)
    assert.equal((await latest()).savedVsRandom, audit.negativeExample.savedVsRandom)
    assert.ok((await latest()).savedVsRandom < 0)
    assert.ok(await page.locator('.metrics .negative').count() > 0)
    assert.match(await page.locator('.decision h2').innerText(), /azar/)
    checks.push('Caso real donde dirigida pierde: diferencia negativa y decisión honesta visibles')
    await page.getByRole('button', { name: 'Restablecer escenario oficial' }).click()
    await run(); await wait(7)
    await page.setViewportSize({ width: 390, height: 844 })
    await page.screenshot({ path: path.join(out, 'movil.png'), fullPage: true }); await page.screenshot({ path: path.join(out, 'movil-vista.png') })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false)
    await page.getByLabel('Semilla', { exact: true }).focus()
    await page.keyboard.press('Tab')
    assert.equal(await page.locator('[name=runs]').evaluate(el => el === document.activeElement), true)
    checks.push('390 px sin desbordamiento de página y navegación por teclado')
    await page.emulateMedia({ media: 'print' })
    assert.equal(await page.locator('.controls').isVisible(), false)
    assert.equal(await page.locator('.decision').isVisible(), true)
    checks.push('Vista imprimible conserva resultados y oculta controles')
    assert.deepEqual(errors, [])
    const record = { checks, pageErrors: errors, passed: checks.length }
    await fs.writeFile(path.join(out, 'verificacion.json'), JSON.stringify(record, null, 2))
    console.log(JSON.stringify(record, null, 2))
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exit(1) })


