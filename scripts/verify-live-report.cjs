const {chromium}=require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const fs=require('node:fs/promises')
const path=require('node:path')
const assert=require('node:assert/strict')
;(async()=>{
 const browser=await chromium.launch({headless:true,channel:process.env.UI_BROWSER_CHANNEL||undefined})
 try {
  const page=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'reduce'})
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  await page.route('https://tile.openstreetmap.org/**',r=>r.abort())
  await page.goto(process.env.UI_BASE_URL||'http://127.0.0.1:4176/')
  const map=page.locator('.live-map'),slider=page.locator('#map-day')
  await map.waitFor({timeout:60000})
  // Autoplay must work even while the map is below the fold and reduced motion is enabled.
  await page.waitForFunction(()=>Number(document.querySelector('#map-day').value)>=2)
  await map.getByRole('combobox',{name:/Velocidad/}).selectOption('500')
  assert.equal(await map.getByRole('combobox',{name:/Velocidad/}).inputValue(),'500')
  await map.getByRole('combobox',{name:/Velocidad/}).selectOption('333')
  await map.getByRole('button',{name:'Ver en modo presentación'}).click()
  assert.equal(await page.locator('.live-map.presentation').count(),1)
  const day=Number(await slider.inputValue())
  await page.waitForFunction(day=>Number(document.querySelector('#map-day').value)>day,day)
  assert.match(await map.locator('.map-day-popup').innerText(),/DÍA/)
  await page.keyboard.press('Escape')
  assert.equal(await page.locator('.live-map.presentation').count(),0)
  await page.evaluate(()=>scrollTo(0,0))
  await page.waitForFunction(()=>document.querySelector('#map-day').value==='90',null,{timeout:45000})
  await map.getByRole('button',{name:'Reproducir mapa',exact:true}).waitFor()
  const link=map.getByRole('link',{name:'Descargar informe PDF'})
  await link.waitFor({timeout:30000})
  const download=page.waitForEvent('download');await link.click()
  const out=process.env.UI_EVIDENCE_DIR||'docs/evidencia/directo'
  await fs.mkdir(out,{recursive:true})
  const file=path.join(out,'informe-alcalde.pdf');await (await download).saveAs(file)
  const bytes=await fs.readFile(file)
  assert.equal(bytes.subarray(0,5).toString(),'%PDF-')
  assert.deepEqual(errors,[])
  const record={passed:6,checks:['Autoplay offscreen and with reduced motion','Speeds x2 and x3 selectable','Live popup changes with day','Presentation mode and Escape','Full real playback ends at day 90','PDF generated automatically and downloaded'],errors}
  await fs.writeFile(path.join(out,'verificacion-directo.json'),JSON.stringify(record,null,2))
  console.log(JSON.stringify(record))
 } finally {await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1})
